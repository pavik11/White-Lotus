import Foundation

struct SupportResource: Identifiable {
    let id: String
    let name: String
    let summary: String
    let website: URL
}

enum SupportTopic: String, CaseIterable, Identifiable {
    case bullying, connection, feelingLost, basicNeeds

    var id: String { rawValue }

    var title: String {
        switch self {
        case .bullying: return "Bullying or harassment"
        case .connection: return "Lonely or need someone to talk to"
        case .feelingLost: return "Feeling lost or unsure"
        case .basicNeeds: return "Food, housing or practical help"
        }
    }

    var introduction: String {
        switch self {
        case .bullying:
            return "We can keep talking. If you'd like help beyond this chat, these organizations offer guidance and human support for what you're facing."
        case .connection:
            return "We can keep talking. If you're feeling lonely and would like a human listening ear, peer support may be another option."
        case .feelingLost:
            return "We can keep talking about what feels uncertain. If you'd like another perspective, these resources can help you explore support."
        case .basicNeeds:
            return "We can keep talking. For practical needs like food or housing, a local community service may be able to help."
        }
    }

    var resources: [SupportResource] {
        switch self {
        case .bullying: return [SupportResources.stopBullying, SupportResources.namiYouth]
        case .connection: return [SupportResources.namiYouth, SupportResources.warmlines]
        case .feelingLost: return [SupportResources.namiYouth]
        case .basicNeeds: return [SupportResources.community]
        }
    }

    // A convenience suggestion, never a diagnosis or emergency assessment. The user
    // can choose any topic in the directory even when these phrases do not match.
    static func suggested(for text: String) -> Self? {
        let normalized = text.folding(options: [.caseInsensitive, .diacriticInsensitive],
                                      locale: Locale(identifier: "en_US_POSIX"))
            .components(separatedBy: CharacterSet.alphanumerics.inverted)
            .filter { !$0.isEmpty }.joined(separator: " ")
        let padded = " " + normalized + " "
        let matches: ([String]) -> Bool = { phrases in
            phrases.contains { padded.contains(" " + $0 + " ") }
        }
        if matches(["bully", "bullied", "bullying", "cyberbullying", "harassment", "harassed", "picked on", "picking on me", "making fun of me"]) {
            return .bullying
        }
        if matches(["homeless", "housing", "shelter", "food insecurity", "cannot afford food", "can t afford food", "nowhere to stay"]) {
            return .basicNeeds
        }
        if matches(["feel lost", "feeling lost", "no direction", "lack of purpose", "what to do with my life"]) {
            return .feelingLost
        }
        if matches(["lonely", "loneliness", "isolated", "no one to talk to", "someone to talk to", "nobody to talk to", "left out", "no friends"]) {
            return .connection
        }
        return nil
    }
}

// Reviewed against these official sources on 2026-10-25. Contact details are
// deliberately linked to their maintained pages rather than generated by Gemini.
// No chat text, saved name, or inferred location is placed in an outbound URL.
enum SupportResources {
    static let stopBullying = SupportResource(
        id: "stopBullying", name: "StopBullying.gov",
        summary: "Guidance for bullying and cyberbullying, including how to involve your school. A school counselor or trusted adult can also help.",
        website: URL(string: "https://www.stopbullying.gov/resources/get-help-now")!)
    static let namiYouth = SupportResource(
        id: "namiYouth", name: "NAMI Teen & Young Adult HelpLine",
        summary: "Peer support, information and resources for teens and young adults going through a difficult time. This is not a crisis service. Check the official page for contact options and hours.",
        website: URL(string: "https://www.nami.org/nami-helpline/teen-young-adult-helpline/")!)
    static let warmlines = SupportResource(
        id: "warmlines", name: "NAMI Warmline Directory",
        summary: "Find peer-run emotional support lines. Hours, age limits and location eligibility vary; check the listing before reaching out.",
        website: URL(string: "https://helplinefaqs.nami.org/article/577-nami-national-warmline-directory")!)
    static let community = SupportResource(
        id: "community", name: "United Way 211",
        summary: "Find local community resources for needs such as food and housing. This is practical support, not a substitute for emergency services.",
        website: URL(string: "https://211.org/")!)
}
